import { existsSync, readdirSync, readFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { OnboardingStepKind } from "../../src/core/types.ts";
import { EV } from "../../src/core/events.ts";
import { termsTemplate } from "../../src/playbook/product.ts";
import { config, TEMPLATE_DIR } from "./fixtures.ts";

const read = (rel: string) => readFileSync(join(TEMPLATE_DIR, rel), "utf8");

/** Loads an import-free template module; the template's own tsconfig is not resolvable from the studio. */
async function loadTemplateModule<T>(rel: string): Promise<T> {
  const js = stripTypeScriptTypes(read(rel));
  return (await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`)) as T;
}

interface TermsModule {
  termsLine(priceString: string, period: "week" | "month" | "year", trialDays: number): string;
  periodFromIso(iso: string | null): string | null;
  trialDaysFromIntro(intro: { price: number; periodUnit: string; periodNumberOfUnits: number; cycles: number } | null): number;
}
let TEMPLATE_EV: Record<string, string>;
let terms: TermsModule;

beforeAll(async () => {
  TEMPLATE_EV = (await loadTemplateModule<{ EV: Record<string, string> }>("src/events.ts")).EV;
  terms = await loadTemplateModule<TermsModule>("src/terms.ts");
});

describe("Expo template", () => {
  it("pins Expo SDK 58 and the native modules it needs", () => {
    const pkg = JSON.parse(read("package.json")) as { main: string; dependencies: Record<string, string> };
    expect(pkg.main).toBe("expo-router/entry");
    expect(pkg.dependencies).toMatchObject({ expo: "~58.0.14", react: "19.3.0", "react-native": "0.88.0", "expo-router": "~58.0.23" });
    for (const dep of [
      "expo-notifications",
      "expo-sharing",
      "expo-image-picker",
      "expo-linking",
      "expo-constants",
      "expo-localization",
      "expo-updates",
      "expo-status-bar",
      "react-native-view-shot",
      "react-native-safe-area-context",
      "react-native-screens",
      "react-native-purchases",
      "posthog-react-native",
    ]) {
      expect(pkg.dependencies[dep], dep).toBeDefined();
    }
    expect(pkg.dependencies["react-native-purchases"]).toMatch(/^\^10\./);
    expect(pkg.dependencies["posthog-react-native"]).toMatch(/^\^4\./);
    expect(Object.keys(pkg.dependencies).some((d) => /tracking-transparency|advertising/i.test(d))).toBe(false);
  });

  it("ships source only", () => {
    expect(existsSync(join(TEMPLATE_DIR, "node_modules"))).toBe(false);
    expect(existsSync(join(TEMPLATE_DIR, "server", "node_modules"))).toBe(false);
    for (const route of ["_layout", "index", "onboarding", "paywall", "home", "result", "settings"]) expect(existsSync(join(TEMPLATE_DIR, "app", `${route}.tsx`))).toBe(true);
  });

  it("copies the canonical event names exactly", () => {
    expect(TEMPLATE_EV).toEqual(EV);
  });

  it("mirrors every onboarding step kind and renders each one", () => {
    const types = read("src/types.ts");
    const onboarding = read("app/onboarding.tsx");
    for (const kind of OnboardingStepKind.options) {
      expect(types).toContain(`"${kind}"`);
      expect(onboarding).toContain(`case "${kind}":`);
    }
  });

  it("renders paywall terms with the same wording as termsTemplate", () => {
    const { periodFromIso, termsLine, trialDaysFromIntro } = terms;
    for (const entry of config.monetization.ladder) {
      expect(termsLine("{price}", entry.period, entry.trialDays)).toBe(termsTemplate(entry));
    }
    expect(periodFromIso("P1W")).toBe("week");
    expect(periodFromIso("P7D")).toBe("week");
    expect(periodFromIso("P1M")).toBe("month");
    expect(periodFromIso("P1Y")).toBe("year");
    expect(periodFromIso("P12M")).toBe("year");
    expect(periodFromIso(null)).toBeNull();
    expect(trialDaysFromIntro({ price: 0, periodUnit: "DAY", periodNumberOfUnits: 3, cycles: 1 })).toBe(3);
    expect(trialDaysFromIntro({ price: 0, periodUnit: "WEEK", periodNumberOfUnits: 1, cycles: 1 })).toBe(7);
    expect(trialDaysFromIntro({ price: 0.99, periodUnit: "WEEK", periodNumberOfUnits: 1, cycles: 1 })).toBe(0);
    expect(trialDaysFromIntro(null)).toBe(0);
  });

  it("keeps the compliance surfaces in the screens", () => {
    const paywall = read("app/paywall.tsx");
    expect(paywall).toContain("chosen.terms");
    for (const text of ["Restore purchases", "Manage subscription", "Terms", "Privacy", "showCloseAfterSeconds", "APP_EVENTS.paywallView", "APP_EVENTS.trialStart", "APP_EVENTS.transactionAbandon"]) {
      expect(paywall).toContain(text);
    }
    expect(paywall).not.toMatch(/\$\d/);
    const result = read("app/result.tsx");
    for (const text of ["Generated by AI", "Report this result", "captureRef", "Sharing.shareAsync", "spec.share.watermark", "APP_EVENTS.shareFirst"]) expect(result).toContain(text);
    const settings = read("app/settings.tsx");
    for (const text of ["Restore purchases", "Manage subscription", "Delete my data", "Allow AI processing", "Privacy policy", "Terms of use", "supportEmail"]) expect(settings).toContain(text);
    const onboarding = read("app/onboarding.tsx");
    expect(onboarding).toContain("studio.aiProviders");
    expect(onboarding.indexOf("requestPermission()")).toBeGreaterThan(onboarding.indexOf("async function notifyYes"));
    const notifications = read("src/notifications.ts");
    expect(notifications).toContain('entry.kind === "promotional" && !promo');
  });

  it("never asks for tracking", () => {
    const sources = ["app.config.ts", ...readdirSync(join(TEMPLATE_DIR, "app")).map((f) => `app/${f}`), ...readdirSync(join(TEMPLATE_DIR, "src")).map((f) => `src/${f}`)];
    for (const file of sources) {
      const text = read(file);
      expect(text, file).not.toMatch(/NSUserTrackingUsageDescription|requestTrackingPermissions|advertisingId|getAdvertisingId|IDFA/);
    }
    expect(read("app.config.ts")).toContain("com.google.android.gms.permission.AD_ID");
  });

  it("configures the app from spec.json and studio.json", () => {
    const appConfig = read("app.config.ts");
    for (const text of [
      'import specJson from "./spec.json"',
      'import studioJson from "./studio.json"',
      "scheme: studio.slug",
      "supportsTablet: false",
      "usesNonExemptEncryption: false",
      "applinks:${studio.deepLinkDomain}",
      "privacyManifests: studio.privacyManifest",
      "pathPrefix: spec.share.deepLinkPath",
      '"expo-router"',
      '"expo-notifications"',
      'policy: "fingerprint"',
      "https://u.expo.dev/${studio.easProjectId}",
      "posthogApiKeyEnv",
      "revenueCatKeyEnv",
      "backendUrl",
    ]) {
      expect(appConfig, text).toContain(text);
    }
    const eas = JSON.parse(read("eas.json")) as { build: Record<string, { autoIncrement?: boolean }>; submit: Record<string, unknown> };
    for (const profile of ["development", "preview", "production"]) expect(eas.build[profile]?.autoIncrement).toBe(true);
    expect(eas.submit.production).toBeDefined();
  });

  it("calls Claude from the server with the official SDK at low effort and no thinking parameter", () => {
    const server = read("server/src/index.ts");
    expect(server).toContain('from "@anthropic-ai/sdk"');
    expect(server).toContain('output_config: { effort: "low"');
    expect(server).not.toMatch(/thinking:/);
    const pkg = JSON.parse(read("server/package.json")) as { dependencies: Record<string, string> };
    expect(pkg.dependencies["@anthropic-ai/sdk"]).toBeDefined();
  });
});
