export function legalMarkdown(doc: LegalDoc): string {
  const out = [`# ${doc.title}`, "", `_Last updated: ${doc.updated}_`, "", doc.intro, ""];
  for (const s of doc.sections) {
    out.push(`## ${s.heading}`, "");
    for (const p of s.paragraphs) out.push(p, "");
    if (s.bullets?.length) out.push(...s.bullets.map((b) => `- ${b}`), "");
  }
  return out.join("\n");
}

export function escapeHtml(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** Bare URLs and emails become links; everything else is escaped. */
function inlineHtml(text: string): string {
  return escapeHtml(text).replace(/(https?:\/\/[^\s<]+[^\s<.,;)])|([\w.+-]+@[\w-]+(?:\.[\w-]+)+)/g, (m, url: string | undefined) =>
    url ? `<a href="${m}">${m}</a>` : `<a href="mailto:${m}">${m}</a>`,
  );
}

export function legalHtmlBody(doc: LegalDoc): string {
  const out = [`<h1>${escapeHtml(doc.title)}</h1>`, `<p class="muted">Last updated: ${escapeHtml(doc.updated)}</p>`, `<p>${inlineHtml(doc.intro)}</p>`];
  for (const s of doc.sections) {
    out.push(`<h2>${escapeHtml(s.heading)}</h2>`);
    for (const p of s.paragraphs) out.push(`<p>${inlineHtml(p)}</p>`);
    if (s.bullets?.length) out.push(`<ul>${s.bullets.map((b) => `<li>${inlineHtml(b)}</li>`).join("")}</ul>`);
  }
  return out.join("\n");
}
