/**
 * Privacy policy and terms of use, assembled from fixed clauses plus facts from the spec,
 * the data inventory, the price ladder and the company config. Never LLM-written: the only
 * spec fields used are names and identifiers, never generated prose.
 *
 * Covers Apple 3.1.2 and 5.1.1(i), California's automatic renewal law (Bus. & Prof. Code
 * 17602) and CCPA notice-at-collection, ROSCA, and the AI disclosure of Apple 5.1.2(i).
 */
import type { PriceLadderEntry, StudioConfig } from "../config/schema.ts";
import type { AppSpec, DataUse } from "../core/types.ts";
import { termsTemplate } from "../playbook/product.ts";
import { collectedData, DATA_LABELS, PURPOSE_LABELS, RECIPIENTS, recipients } from "./privacy.ts";
import type { VentureUrls } from "./studio.ts";

export interface LegalSection {
  heading: string;
  paragraphs: string[];
  bullets?: string[];
}

export interface LegalDoc {
  title: string;
  /** YYYY-MM-DD */
  updated: string;
  intro: string;
  sections: LegalSection[];
}

export interface LegalInput {
  spec: AppSpec;
  config: StudioConfig;
  urls: VentureUrls;
  /** YYYY-MM-DD of the build. */
  updated: string;
  /** Paywall products resolved from the price ladder. */
  products: PriceLadderEntry[];
}

/** The studio entity's jurisdiction (core/store seeds one US-DE entity). */
export const GOVERNING_LAW = "the State of Delaware, United States";

const APPLE_MANAGE = "https://apps.apple.com/account/subscriptions";
const PLAY_MANAGE = "https://play.google.com/store/account/subscriptions";
const PERIOD_NAME: Record<PriceLadderEntry["period"], string> = { week: "Weekly", month: "Monthly", year: "Annual" };

function retention(days: number): string {
  if (days <= 0) return "not stored after your request is processed";
  if (days % 365 === 0) return `kept for up to ${days / 365} year${days === 365 ? "" : "s"}`;
  return `kept for up to ${days} days`;
}

function dataLine(d: DataUse): string {
  const to = d.sentTo.map((r) => RECIPIENTS[r].name).join(", ");
  const linked = d.linkedToUser ? "linked to your app account" : "not linked to your identity";
  return `${DATA_LABELS[d.dataType]}: used ${PURPOSE_LABELS[d.purpose]}; shared with ${to}; ${retention(d.retentionDays)}; ${linked}.`;
}

/** One terms line per product, from termsTemplate with the price placeholder spelled out. */
export function subscriptionLines(products: PriceLadderEntry[]): string[] {
  return products.map((p) => {
    const label = p.trialDays > 0 ? `${PERIOD_NAME[p.period]} plan with a ${p.trialDays}-day free trial` : `${PERIOD_NAME[p.period]} plan`;
    return `${label}: ${termsTemplate(p).replace(/\{price\}\/(\w+)/, "the price per $1 shown in the app before you confirm the purchase")}`;
  });
}

