function jitter(rng: Rng, v: number, by: number): number {
  return Math.round(Math.min(1, Math.max(0, v + rng.uniform(-by, by))) * 100) / 100;
}

/** A complete Idea from an archetype; numeric wedge facts get small seeded jitter. */
export function ideaFromArchetype(a: IdeaArchetype, rng: Rng, titleOverride?: string): Idea {
  const [coPresence, discoverable, inflectionPoint, obsessive, urgency, ownedReach] = a.wedge.factors;
  return {
    title: titleOverride ?? a.title,
    oneLiner: a.oneLiner,
    coreNeed: a.coreNeed,
    secondaryNeeds: [...(a.secondaryNeeds ?? [])],
    wedge: {
      name: a.wedge.name,
      kind: a.wedge.kind,
      description: a.wedge.description,
      minAge: a.wedge.minAge,
      maxAge: a.wedge.maxAge,
      locale: "en-US",
      creatorNiche: a.wedge.creatorNiche,
      estimatedReachableCreators: Math.max(0, Math.round(a.wedge.creators * rng.uniform(0.85, 1.15))),
      coPresence: jitter(rng, coPresence, 0.05),
      discoverable: jitter(rng, discoverable, 0.05),
      inflectionPoint: jitter(rng, inflectionPoint, 0.05),
      obsessive: jitter(rng, obsessive, 0.05),
      urgency: jitter(rng, urgency, 0.05),
      ownedReach: jitter(rng, ownedReach, 0.05),
    },
    verdictMoment: a.verdictMoment,
    aiCapability: a.aiCapability,
    valueConditions: [...a.valueConditions],
    singlePlayerValue: a.singlePlayerValue ?? true,
    minFriendsForValue: a.minFriendsForValue ?? 0,
    requiresPartnership: a.requiresPartnership ?? false,
    primaryChannel: a.primaryChannel ?? "creator_ugc",
    secondaryChannels: [...(a.secondaryChannels ?? ["share_loop", "app_store_search", "owned_social"])],
    shareArtifact: a.shareArtifact,
    hookExamples: [...a.hooks],
    interaction: { ...BASE_INTERACTION, ...a.interaction },
    monetization: { model: a.monetization ?? "hard_paywall", payFor: a.payFor },
    sensitiveDomains: [...(a.sensitive ?? [])],
    differentiation: a.differentiation,
  };
}
