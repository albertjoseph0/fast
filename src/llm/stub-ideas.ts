/**
 * Idea archetypes for the deterministic stub LLM, modelled on real single-player AI
 * verdict categories (Vert's Astra, Plug and Strum; Cal AI; Quittr; plant and card
 * scanners). About a quarter are deliberately flawed so the idea gates have something to
 * reject: meetup apps, live video, paid-only distribution, partnership dependencies, teen
 * school apps, symptom diagnosis and ideas with too many value conditions.
 */
import type { ChannelKind, CoreNeed, Idea, InteractionBudget, SensitiveDomain } from "../core/types.ts";
import type { Rng } from "../core/rng.ts";

type WedgeKind = Idea["wedge"]["kind"];

export interface IdeaArchetype {
  title: string;
  oneLiner: string;
  coreNeed: CoreNeed;
  secondaryNeeds?: CoreNeed[];
  wedge: {
    name: string;
    kind: WedgeKind;
    description: string;
    minAge: number;
    maxAge: number;
    creatorNiche: string;
    creators: number;
    /** coPresence, discoverable, inflectionPoint, obsessive, urgency, ownedReach (0..1). */
    factors: [number, number, number, number, number, number];
  };
  verdictMoment: string;
  aiCapability: string;
  valueConditions: string[];
  shareArtifact: string;
  hooks: string[];
  payFor: string;
  monetization?: Idea["monetization"]["model"];
  sensitive?: SensitiveDomain[];
  differentiation: string;
  interaction?: Partial<InteractionBudget>;
  primaryChannel?: ChannelKind;
  secondaryChannels?: ChannelKind[];
  singlePlayerValue?: boolean;
  minFriendsForValue?: number;
  requiresPartnership?: boolean;
  /** Words matched against discovery signals to bias selection. */
  tags: string[];
  /** Why the gates should reject it (flawed archetypes only). */
  flaw?: string;
}

