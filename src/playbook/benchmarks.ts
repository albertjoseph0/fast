const BY_ID = new Map(BENCHMARKS.map((b) => [b.id, b]));

/** Look up a benchmark by id. Throws on an unknown id so a typo cannot silently cite nothing. */
export function benchmark(id: string): Benchmark {
  const found = BY_ID.get(id);
  if (!found) throw new Error(`unknown benchmark: ${id}`);
  return found;
}
